"""A fixed live-roster scenario for the KAN-116 "live is unchanged" golden test.

Deterministic synthetic bars for every declared ticker (opens gap away from the
prior close, so some limits go unfilled), deterministic fundamentals and
earnings, an explicit regime (neutral, turning bull 40 sessions before the
end), and a hydrated ``PortfolioContext`` per sleeve.

The contexts exercise every branch the live path reads, and every exit
threshold from BOTH sides — one tick (0.05 percentage points) or one session
either side of the line, at the parameters the live roster uses in a bull
regime:

* trailing stops: momentum 10%, sector_rotation 8%, thematic_momentum 10%,
  quality_value 12%, earnings_drift 6%;
* max-loss stops: momentum 8%, thematic_momentum 8%;
* earnings_drift's 20-session hold (19 and 20 sessions after the fill);
* thematic_momentum's 50-day MA cross (two tickers whose last closes sit just
  above and just below their MA);
* tail_risk_hedge's regime at entry (filled on the last neutral session vs
  the first bull one) and its allocation (a bear-only ETF held in bull);
* momentum's bear-ticker exit outside a bear regime;

plus a holding past a stop, a fresh holding, an old holding, a pending buy and
a partly covering pending sell.

``live_signals()`` returns what ``build_portfolios(portfolio_contexts=...)`` —
the 05:15 run's roster — emits for every sleeve and ticker on the last three
sessions. The golden file beside the test was generated by running this module
against the parent commit (origin/main 6b93d6a, before KAN-116, via
``git archive``), so the test proves the live path's decisions are
byte-identical after the change — including on which side of each threshold
every holding falls.
"""
from __future__ import annotations

import hashlib
import json
import random
from datetime import date, timedelta

from backtest.portfolio_context import HeldPosition, PendingOrder, PortfolioContext

SEED = 116
N_SESSIONS = 260
#: Sessions before the end at which the regime turns from neutral to bull.
BULL_FROM = N_SESSIONS - 40
#: One tick either side of a threshold, as a fraction of price.
TICK = 0.0005
#: Thematic tickers whose last closes are pinned just above / below their 50-day MA.
MA_ABOVE, MA_BELOW = "LIT", "PBW"
CUTOFFS = (N_SESSIONS - 3, N_SESSIONS - 2, N_SESSIONS - 1)


def _sessions() -> list[date]:
    out, d = [], date(2025, 1, 2)
    while len(out) < N_SESSIONS:
        if d.weekday() < 5:
            out.append(d)
        d += timedelta(days=1)
    return out


def _h(text: str) -> int:
    return int(hashlib.sha256(text.encode()).hexdigest()[:8], 16)


def universe() -> list[str]:
    from shared.universe import ACTIVE_SLEEVES, UNIVERSE_REGISTRY

    return sorted({t for s in ACTIVE_SLEEVES for t in UNIVERSE_REGISTRY[s]})


def regime_by_date() -> dict[date, str]:
    return {d: ("neutral" if i < BULL_FROM else "bull") for i, d in enumerate(_sessions())}


def _pin_to_ma(rows: list[dict], sign: float) -> None:
    """Set the last closes so each sits one tick ``sign``-side of its own 50-day MA."""
    for i in CUTOFFS:
        prior = sum(r["close"] for r in rows[i - 49:i])
        eps = sign * 1e-4
        close = prior * (1 + eps) / (49 - eps)
        rows[i] = {**rows[i], "close": close,
                   "high": max(rows[i]["open"], close) * 1.006,
                   "low": min(rows[i]["open"], close) * 0.994}


def bars_by_ticker() -> dict[str, list[dict]]:
    rng = random.Random(SEED)
    out = {}
    for ticker in universe():
        drift = rng.uniform(-0.0008, 0.0020)
        price = rng.uniform(20.0, 300.0)
        rows = []
        for day in _sessions():
            open_ = price * (1.0 + rng.gauss(0.0, 0.006))
            price = open_ * (1.0 + drift + rng.gauss(0.0, 0.014))
            rows.append({
                "date": day, "open": round(open_, 4),
                "high": round(max(open_, price) * 1.004, 4),
                "low": round(min(open_, price) * 0.996, 4),
                "close": round(price, 4), "volume": 1_000_000,
            })
        out[ticker] = rows
    _pin_to_ma(out[MA_ABOVE], +1.0)
    _pin_to_ma(out[MA_BELOW], -1.0)
    return out


def fundamentals_lookup(ticker: str, as_of: date) -> dict | None:
    h = _h(ticker)
    if h % 11 == 0:
        return None
    return {
        "roe": 0.02 + (h % 37) / 100.0,
        "debt_equity": (h % 23) / 10.0,
        "profit_margin": 0.01 + (h % 29) / 100.0,
    }


def earnings_lookup(ticker: str, as_of: date) -> dict | None:
    h = _h(ticker + as_of.isoformat())
    if h % 9 != 0:
        return None
    return {"surprise_pct": float(h % 17) - 3.0, "actual_eps": 1.0, "estimate_eps": 1.0}


def _trailing(close: float, drawdown: float) -> tuple[float, float]:
    """(entry, peak) for a holding ``drawdown`` below its peak, in profit at the peak."""
    peak = close / (1.0 - drawdown)
    return peak * 0.8, peak


def _above_ma(rows: list[dict], period: int = 50) -> bool:
    closes = [r["close"] for r in rows[-period:]]
    return rows[-1]["close"] > sum(closes) / len(closes)


def _edges(sleeve: str, names: list[str], bars: dict[str, list[dict]], sessions: list[date],
           cut: int) -> dict[str, HeldPosition]:
    """Holdings one tick / one session either side of this sleeve's exit lines.

    Each edge holding is placed so that no OTHER exit masks the one it tests:
    thematic stop edges sit on tickers above their 50-day MA, and earnings
    drift's stop edges were filled 5 sessions ago, well inside its hold.
    """
    pos: dict[str, HeldPosition] = {}
    last = {t: bars[t][-1]["close"] for t in names}
    free = iter(
        n for n in names[4:]
        if n not in (MA_ABOVE, MA_BELOW)
        and (sleeve != "thematic_momentum" or _above_ma(bars[n]))
    )
    entry_date = sessions[cut - (5 if sleeve == "earnings_drift" else 30)]

    def trail(pct: float) -> None:
        for side in (+1, -1):
            t = next(free)
            entry, peak = _trailing(last[t], pct + side * TICK)
            pos[t] = HeldPosition(6.0, entry, peak, entry_date)

    def max_loss(pct: float) -> None:
        for side in (+1, -1):
            t = next(free)
            entry = last[t] / (1.0 - (pct + side * TICK))
            pos[t] = HeldPosition(6.0, entry, entry, entry_date)

    if sleeve == "momentum":
        trail(0.10)
        max_loss(0.08)
        pos["SH"] = HeldPosition(4.0, last["SH"], last["SH"], entry_date)
    elif sleeve == "sector_rotation":
        trail(0.08)
    elif sleeve == "thematic_momentum":
        trail(0.10)
        max_loss(0.08)
        for t in (MA_ABOVE, MA_BELOW):
            pos[t] = HeldPosition(6.0, last[t], last[t], entry_date)
    elif sleeve == "quality_value":
        trail(0.12)
    elif sleeve == "earnings_drift":
        trail(0.06)
        # 20 and 19 sessions after the fill on the decision bar.
        for back in (20, 19):
            t = next(free)
            pos[t] = HeldPosition(6.0, last[t], last[t], sessions[cut - back])
    return pos


def contexts(bars: dict[str, list[dict]]) -> dict[str, PortfolioContext]:
    from shared.universe import ACTIVE_SLEEVES, UNIVERSE_REGISTRY

    sessions = _sessions()
    out = {}
    for sleeve in ACTIVE_SLEEVES:
        names = sorted(UNIVERSE_REGISTRY[sleeve])
        last = {t: bars[t][-1]["close"] for t in names}
        cut = len(next(iter(bars.values()))) - 1
        if sleeve == "tail_risk_hedge":
            # GLD filled on the last neutral session (regime changed: exit),
            # TLT on the first bull one (unchanged: hold), SH is bear-only
            # (not in the bull allocation: exit).
            positions = {
                "GLD": HeldPosition(10.0, last["GLD"], last["GLD"], sessions[BULL_FROM - 1]),
                "TLT": HeldPosition(5.0, last["TLT"], last["TLT"], sessions[BULL_FROM]),
                "SH": HeldPosition(7.0, last["SH"], last["SH"], sessions[BULL_FROM]),
            }
            if cut == CUTOFFS[0]:
                # One session holding no TLT, so the bull allocation is bought.
                del positions["TLT"]
            pending = {
                "buy": PendingOrder("PSQ", "buy", 3.0, last["PSQ"], f"{sleeve}-buy"),
                "sell": PendingOrder("GLD", "sell", 4.0, last["GLD"], f"{sleeve}-sell"),
            }
        else:
            stopped, fresh, old, pending_buy = names[0], names[1], names[2], names[3]
            positions = {
                stopped: HeldPosition(10.0, last[stopped] * 1.1, last[stopped] * 1.4, sessions[-60]),
                fresh: HeldPosition(5.0, last[fresh], last[fresh], sessions[cut - 1]),
                old: HeldPosition(7.0, last[old] * 0.9, last[old] * 1.02, sessions[-45]),
                **_edges(sleeve, names, bars, sessions, cut),
            }
            pending = {
                "buy": PendingOrder(pending_buy, "buy", 3.0, last[pending_buy], f"{sleeve}-buy"),
                "sell": PendingOrder(stopped, "sell", 4.0, last[stopped], f"{sleeve}-sell"),
            }
        out[sleeve] = PortfolioContext(
            positions=positions, pending_orders=pending,
            sleeve_budget=10_000.0, reserved_notional=100.0,
        )
    return out


def live_signals() -> dict[str, dict]:
    """``{"<cutoff>|<sleeve>|<ticker>": signal}`` for every non-None signal."""
    from scripts.run_paper import build_portfolios

    bars = bars_by_ticker()
    regime = regime_by_date()
    out: dict[str, dict] = {}
    for cut in CUTOFFS:
        window = {t: rows[: cut + 1] for t, rows in bars.items()}
        roster = build_portfolios(
            capital=100_000.0,
            bars_by_ticker=window,
            regime_by_date=regime,
            fundamentals_lookup=fundamentals_lookup,
            earnings_lookup=earnings_lookup,
            portfolio_contexts=contexts(window),
        )
        for sleeve, config in sorted(roster.items()):
            for ticker in sorted(window):
                signal = config.signals_fn(ticker, window[ticker])
                if signal is not None:
                    key = f"{window[ticker][-1]['date'].isoformat()}|{sleeve}|{ticker}"
                    out[key] = json.loads(json.dumps(signal, sort_keys=True, default=str))
    return out
